const holes = (s) => [...new Set(String(s).match(/\{[a-z_]+\}/g) || [])].sort().join('');
export function agentLabelsFrom(translated) {
  const out = {};
  for (const k of AGENT_LABEL_KEYS) {
    const en = AGENT_EN[k] ?? AGENT_VALUE_EN[k];
    const v = translated?.[AGENT_LABEL_PREFIX + k];
    if (typeof v === 'string' && v.trim() && holes(v) === holes(en)) out[k] = v;
  }
  return out;
}

// _doc_text: the translated label when it keeps every {placeholder}, else the English; then the values are filled in.
// Every label goes through the wording rule (REQ-529c), so the retired product name is never printed.
export function agentText(labels, key, values = {}) {
  const en = AGENT_EN[key] ?? AGENT_VALUE_EN[key] ?? key;
  const tr = labels?.[key];
  let text = typeof tr === 'string' && tr.trim() && holes(tr) === holes(en) ? tr : en;
  for (const [name, value] of Object.entries(values)) text = text.split(`{${name}}`).join(String(value));
  return aiWording(text);
}

