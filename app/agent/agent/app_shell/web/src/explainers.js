export function explainerFor(kind) {
  return Object.prototype.hasOwnProperty.call(EXPLAINERS, kind) ? EXPLAINERS[kind] : null;
}

// The term's plain meaning for one kind, matched without regard to case; null when the kind does not define it.
export function termFor(kind, term) {
  const e = explainerFor(kind);
  const want = String(term || '').trim().toLowerCase();
  return (e && e.terms.find((x) => x.term.toLowerCase() === want)) || null;
}
