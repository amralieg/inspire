def summarize_for_owner(spark, ctx, evaluation, out=print, show=None):
    table = ctx["output_table"]
    tier_rows = spark.sql(f"SELECT priority_tier, COUNT(*) AS n FROM {table} WHERE run_id = '{ctx['run_id']}' GROUP BY priority_tier").collect()
    tiers = {r["priority_tier"]: int(r["n"]) for r in tier_rows}
    aggregates = {"rows": sum(tiers.values()), "tiers": tiers}
    text = owner_summary_text(ctx, aggregates, evaluation)
    ok, note = ai_endpoint_status(ctx.get("ai_endpoint"))
    if ok:
        prompt = ("Rewrite these facts as a three-sentence briefing for the decision owner. Keep every number exactly as given "
                  "and add no number, cause or claim that is not given. Never write an em dash. Facts: " + text)
        try:
            while True:
                frame = spark.sql(f"SELECT ai_query('{ctx['ai_endpoint']}', {inspire_sql_literal(prompt)}, "
                                  f"modelParameters => {ai_model_parameters(ctx, 220)}, failOnError => false) AS r")
                row = frame.selectExpr(f"r.{_inspire_response_field(frame, 'r')} AS text", "r.errorMessage AS error").collect()[0]
                if ctx.get("ai_temperature_supported", True) and inspire_temperature_rejected(row["error"]):
                    _inspire_drop_temperature(ctx, ctx["ai_endpoint"], out)
                    continue
                break
            if row["text"] and not row["error"]:
                text = str(row["text"]).strip()
            elif row["error"]:
                out(f"AI summary skipped ({str(row['error'])[:200]}); showing the template summary.")
        except Exception as exc:
            out(f"AI summary skipped ({str(exc)[:200]}); showing the template summary.")
    else:
        out(f"AI summary skipped: {note}.")
    out(text)
    display_fn = show if show is not None else globals().get("display")
    top = spark.sql(f"SELECT `rank`, entity_label, `value`, priority_tier, top_reasons, recommended_action, explanation FROM {table} "
                    f"WHERE run_id = '{ctx['run_id']}' ORDER BY `rank`, entity_id LIMIT 20")
    if display_fn:
        display_fn(top)
    try:
        import matplotlib.pyplot as plt
        fig, ax = plt.subplots(figsize=(5, 2.5))
        ax.bar(list(INSPIRE_PRIORITY_TIERS), [tiers.get(t, 0) for t in INSPIRE_PRIORITY_TIERS], color=["#c0392b", "#f39c12", "#7f8c8d"])
        ax.set_title("Rows by priority tier")
        plt.show()
    except ImportError:
        out("matplotlib is not available; the chart is skipped.")
    return {"summary": text, "aggregates": aggregates}


