def _inspire_column_identifier(name):
    column = str(name or "").replace("`", "").strip().split(".")[-1].strip()
    if not column:
        raise ValueError(f"a runtime assumption needs a column name, got {name!r}")
    return "`" + column.replace("`", "``") + "`"


def runtime_assumption_sql(assumption):
    kind = str((assumption or {}).get("kind") or "").strip().upper()
    if kind not in INSPIRE_ASSUMPTION_RULES:
        raise ValueError(f"unknown runtime assumption kind {kind!r}; known kinds: {sorted(INSPIRE_ASSUMPTION_RULES)}")
    table = inspire_table_name(assumption.get("table"))
    column = _inspire_column_identifier(assumption.get("column"))
    if kind in ("KEY_HAS_REPEATED_ROWS", "KEY_HAS_SINGLE_ROWS"):
        having = "> 1" if kind == "KEY_HAS_REPEATED_ROWS" else "= 1"
        return (f"SELECT COUNT(*) AS observed FROM (SELECT {column} FROM {table} WHERE {column} IS NOT NULL "
                f"GROUP BY {column} HAVING COUNT(*) {having})")
    if kind == "COLUMN_HAS_TWO_VALUES":
        return f"SELECT COUNT(DISTINCT {column}) AS observed FROM {table}"
    return f"SELECT COUNT({column}) AS observed FROM {table}"


def check_runtime_assumptions(spark, ctx, assumptions):
    checks = []
    for assumption in assumptions or []:
        kind = str(assumption.get("kind") or "").strip().upper()
        sql = runtime_assumption_sql(assumption)
        name, required, template = INSPIRE_ASSUMPTION_RULES[kind]
        rows = spark.sql(sql).collect()
        observed = rows[0]["observed"] if rows else None
        column = str(assumption.get("column") or "").replace("`", "").split(".")[-1]
        table = str(assumption.get("table") or "").replace("`", "")
        statement = " ".join(str(assumption.get("statement") or "the use case depends on this data shape").split())
        message = template.format(column=column, table=table, observed=_inspire_fmt(observed), statement=statement)
        _inspire_check(checks, f"assumption: {column} {name}", observed, required, ">=", message)
    failures = [c for c in checks if not c["passed"]]
    report = {"family": str((ctx or {}).get("family") or ""), "status": "not_ready" if failures else "ready",
              "checks": checks, "assumptions": list(assumptions or [])}
    if failures:
        raise InspireReadinessStop(failures, report)
    return report


def accept_candidate(family, metrics, baseline=None, thresholds=None, technique=""):
    family = str(family).upper()
    th = _inspire_thresholds(family, thresholds)
    m, b = dict(metrics or {}), dict(baseline or {})
    checks = []
    fallback = "reject"
    if family == "A":
        if str(technique) == "Survival Analysis" or "c_index" in m:
            c, bc = _inspire_num(m.get("c_index")), _inspire_num(b.get("c_index"))
            _inspire_check(checks, "concordance index", c, th["min_c_index"], ">=",
                           f"The model ranks outcomes correctly {_inspire_fmt(c)} of the time; at least {th['min_c_index']} is required.")
            _inspire_check(checks, "gain over the simple baseline", None if c is None or bc is None else c - bc,
                           th["min_auc_gain"], ">=", f"The model beats the simple baseline by less than {th['min_auc_gain']}.")
        else:
            auc, pr, rate, bauc = (_inspire_num(m.get("auc")), _inspire_num(m.get("pr_auc")),
                                   _inspire_num(m.get("class_rate")), _inspire_num(b.get("auc")))
            _inspire_check(checks, "out-of-time AUC", auc, th["min_auc"], ">=",
                           f"Out-of-time AUC is {_inspire_fmt(auc)}; at least {th['min_auc']} is required.")
            _inspire_check(checks, "PR-AUC versus class rate", pr, None if rate is None else th["min_pr_auc_lift"] * rate, ">=",
                           f"PR-AUC is {_inspire_fmt(pr)}; at least {th['min_pr_auc_lift']} times the class rate is required.")
            _inspire_check(checks, "AUC gain over the simple baseline", None if auc is None or bauc is None else auc - bauc,
                           th["min_auc_gain"], ">=",
                           f"The model AUC {_inspire_fmt(auc)} beats the simple baseline {_inspire_fmt(bauc)} by less than {th['min_auc_gain']}.")
    elif family == "B":
        _inspire_check(checks, "alerts within the review budget", m.get("alerts"), th["max_alerts_per_run"], "<=",
                       f"The model raises {_inspire_fmt(m.get('alerts'))} alert(s); the review budget is {th['max_alerts_per_run']}.")
        _inspire_check(checks, "top-K stability between two fits", m.get("topk_overlap"), th["min_topk_stability"], ">=",
                       f"Two fits agree on {_inspire_fmt(m.get('topk_overlap'))} of the top alerts; at least {th['min_topk_stability']} is required.")
        if "precision_at_k" in m and "precision_at_k" in b:
            _inspire_check(checks, "precision@K versus baseline", m.get("precision_at_k"), _inspire_num(b.get("precision_at_k")), ">=",
                           "Precision on known cases is below the simple rule.")
    elif family == "C":
        _inspire_check(checks, "silhouette", m.get("silhouette"), th["min_silhouette"], ">=",
                       f"Segments are not distinct enough (silhouette {_inspire_fmt(m.get('silhouette'))}, need {th['min_silhouette']}).")
        _inspire_check(checks, "smallest segment share", m.get("min_segment_share"), th["min_segment_share"], ">=",
                       f"A segment holds {_inspire_fmt(m.get('min_segment_share'))} of entities; every segment needs {th['min_segment_share']}.")
        _inspire_check(checks, "bootstrap stability (ARI)", m.get("bootstrap_ari"), th["min_bootstrap_ari"], ">=",
                       f"Segments change on resampling (ARI {_inspire_fmt(m.get('bootstrap_ari'))}, need {th['min_bootstrap_ari']}).")
    elif family == "D":
        p, bp = _inspire_num(m.get("precision_at_k")), _inspire_num(b.get("precision_at_k"))
        _inspire_check(checks, "precision@K versus popularity", p, None if bp is None else th["min_precision_lift"] * bp, ">=",
                       f"Recommendations hit {_inspire_fmt(p)} versus popularity {_inspire_fmt(bp)}; {th['min_precision_lift']} times popularity is required.")
    elif family == "E":
        fallback = "publish_baseline"
        _inspire_check(checks, "backtest folds", m.get("backtest_folds"), th["min_backtest_folds"], ">=",
                       f"The backtest has {m.get('backtest_folds')} fold(s); at least {th['min_backtest_folds']} are required.")
        _inspire_check(checks, "MASE versus seasonal naive", m.get("mase"), th["max_mase"], "<",
                       f"The forecast does not beat the seasonal naive forecast (MASE {_inspire_fmt(m.get('mase'))}, must be below {th['max_mase']}).")
    elif family == "F":
        _inspire_check(checks, "findings computed", m.get("findings"), 1, ">=", "No finding could be computed.")
        _inspire_check(checks, "multiple-testing correction", m.get("multiple_testing") == "BH", True, "is_true",
                       "Significance was not corrected for multiple tests (Benjamini-Hochberg).")
    elif family == "G":
        _inspire_check(checks, "AI function error rate", m.get("ai_error_rate"), th["max_ai_error_rate"], "<=",
                       f"{_inspire_fmt(m.get('ai_error_rate'))} of the AI calls failed; at most {th['max_ai_error_rate']} is allowed.")
    elif family == "H":
        if "draws" in m:
            _inspire_check(checks, "simulation draws", m.get("draws"), th["min_simulation_draws"], ">=",
                           f"The simulation ran {m.get('draws')} draw(s); at least {th['min_simulation_draws']} are required.")
            _inspire_check(checks, "fixed seed", m.get("seed") is not None, True, "is_true",
                           "The simulation has no fixed seed, so its results cannot be reproduced.")
        else:
            _inspire_check(checks, "feasible plan", m.get("feasible") is True, True, "is_true", "The optimization problem is infeasible.")
            obj, bobj = _inspire_num(m.get("objective")), _inspire_num(b.get("objective"))
            gain = None if obj is None or bobj is None else ((bobj - obj) if str(m.get("sense", "min")).lower() == "min" else (obj - bobj))
            _inspire_check(checks, "better than the current plan", gain, 0.0, ">",
                           f"The plan ({_inspire_fmt(obj)}) is not better than the current plan ({_inspire_fmt(bobj)}).")
    else:
        raise ValueError(f"unknown execution family {family!r}")
    failed = [c for c in checks if not c["passed"]]
    decision = fallback if failed else "accept"
    return {"family": family, "decision": decision, "accepted": decision == "accept", "checks": checks,
            "reasons": [c["message"] for c in failed]}


def resolve_run_action(run_mode, champion=None, as_of_date=None, retrain_days=30, last_drift_psi=None, max_psi=0.25, model_name=""):
    mode = str(run_mode or "Auto").strip().title()
    if mode not in INSPIRE_RUN_MODES:
        raise ValueError(f"run_mode must be one of {list(INSPIRE_RUN_MODES)}, got {run_mode!r}")
    if mode == "Retrain":
        return {"run_mode": mode, "action": "train", "reason": "run mode is Retrain"}
    if mode == "Score":
        if not champion:
            raise InspireNoChampion(model_name, "Run mode Score only uses the approved (champion) model; run once with Auto or Retrain to train and approve one.")
        return {"run_mode": mode, "action": "score", "reason": "run mode is Score: the approved model scores the data"}
    if not champion:
        return {"run_mode": mode, "action": "train", "reason": "no approved model yet"}
    trained = _inspire_date(champion.get("trained_as_of"))
    as_of = _inspire_date(as_of_date) or _ih_dt.date.today()
    if trained is None:
        return {"run_mode": mode, "action": "train", "reason": "the approved model carries no training date"}
    age = (as_of - trained).days
    if age > float(retrain_days):
        return {"run_mode": mode, "action": "train", "reason": f"the approved model is {age} days old (limit {retrain_days:g})"}
    psi = _inspire_num(last_drift_psi)
    if psi is not None and psi >= float(max_psi) - 1e-12:
        return {"run_mode": mode, "action": "train", "reason": f"input drift PSI {psi:.2f} reached the limit {float(max_psi):.2f}"}
    return {"run_mode": mode, "action": "score", "reason": f"the approved model is current ({age} days old, drift below the limit)"}


