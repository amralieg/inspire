def realized_performance(spark, ctx, slots):
    import pandas as pd
    as_of = _inspire_date(ctx["as_of_date"])
    table = ctx["result_table"]
    if ctx["family"] == "A" and not ctx["technique"] == "Survival Analysis":
        from sklearn.metrics import roc_auc_score
        window = int(slots.get("OUTCOME_WINDOW_DAYS") or 0)
        if window <= 0:
            return None
        rows = spark.sql(f"SELECT MAX(as_of_date) AS d FROM {table} WHERE as_of_date <= '{as_of - _ih_dt.timedelta(days=window)}'").collect()
        closed = rows[0]["d"] if rows else None
        if not closed:
            return None
        scores = spark.sql(f"SELECT entity_id, `value` FROM {table} WHERE as_of_date = '{closed}'").toPandas()
        labels = slots["build_label"](ctx, [_inspire_date(closed)]).toPandas()
        joined = scores.merge(labels.astype({"entity_id": str}), on="entity_id", how="inner")
        auc = _inspire_metric(roc_auc_score, joined["label"].astype(int), joined["value"]) if len(joined) else None
        return {"scored_as_of": str(closed), "rows": int(len(joined)), "realized_auc": auc}
    if ctx["family"] == "E":
        past = spark.sql(f"SELECT entity_id, segment_or_item AS period, `value` AS forecast FROM {table} WHERE as_of_date < '{as_of}' "
                         f"AND segment_or_item <= '{as_of}' AND as_of_date = (SELECT MAX(as_of_date) FROM {table} WHERE as_of_date < '{as_of}')").toPandas()
        if past.empty:
            return None
        series = to_pandas_all(slots["build_inputs"](ctx), ctx)
        series["period"] = pd.to_datetime(series["period"]).dt.date.astype(str)
        joined = past.merge(series, on=["entity_id", "period"], how="inner")
        season = int(slots.get("SEASON_LENGTH") or 1)
        errors = []
        for key, group in joined.groupby("entity_id"):
            history = series[(series["entity_id"] == key) & (series["period"] < group["period"].min())].sort_values("period")["value"]
            value = mase(group["value"], group["forecast"], history, season)
            if value is not None:
                errors.append(value)
        return {"forecast_periods": int(len(joined)), "realized_mase": float(sum(errors) / len(errors)) if errors else None}
    return None


