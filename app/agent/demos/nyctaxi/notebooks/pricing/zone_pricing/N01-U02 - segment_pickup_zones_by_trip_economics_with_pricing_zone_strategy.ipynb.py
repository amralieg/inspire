def build_output_frame(scored, ctx, column_map, value_type, method, model_version="", action_by_tier=None, significant_column=None):
    import pandas as pd
    cm = dict(column_map or {})
    for key in ("entity_id", "value"):
        if not cm.get(key) or cm[key] not in scored.columns:
            raise ValueError(f"OUTPUT_COLUMNS['{key}'] must name a column of the scored frame; got {cm.get(key)!r}. "
                             f"Available: {list(scored.columns)}")
    frame = scored.reset_index(drop=True)
    out = pd.DataFrame(index=frame.index)
    out["entity_id"] = frame[cm["entity_id"]].astype(str)
    label = cm.get("entity_label")
    out["entity_label"] = frame[label].astype(str) if label in frame.columns else out["entity_id"]
    out["value"] = pd.to_numeric(frame[cm["value"]], errors="coerce")
    out["value_type"] = str(value_type)
    seg = cm.get("segment_or_item")
    out["segment_or_item"] = frame[seg].fillna("").astype(str) if seg in frame.columns else ""
    rank_by = cm.get("rank_by") or cm["value"]
    if rank_by not in frame.columns:
        raise ValueError(f"OUTPUT_COLUMNS['rank_by'] must name a column of the scored frame; got {rank_by!r}")
    order_values = pd.to_numeric(frame[rank_by], errors="coerce")
    within = cm.get("rank_within")
    ascending = bool(cm.get("rank_ascending", False))
    if within in frame.columns:
        groups = frame[within].astype(str)
        out["rank"] = order_values.groupby(groups).rank(method="first", ascending=ascending, na_option="bottom").astype("int32")
        sizes = groups.map(groups.value_counts())
    else:
        out["rank"] = order_values.rank(method="first", ascending=ascending, na_option="bottom").astype("int32")
        sizes = pd.Series(len(out), index=out.index)
    out["priority_tier"] = assign_priority_tiers(out["rank"].tolist(), sizes.tolist())
    if significant_column and significant_column in frame.columns:
        out.loc[~frame[significant_column].fillna(False).astype(bool), "priority_tier"] = "Monitor"
    reasons = cm.get("top_reasons")
    out["top_reasons"] = frame[reasons].map(_inspire_as_list) if reasons in frame.columns else [[] for _ in range(len(out))]
    actions = dict(action_by_tier or {})
    out["recommended_action"] = out["priority_tier"].map(lambda tier: actions.get(tier, ""))
    out["explanation"] = None
    flag = cm.get("data_quality_flag")
    out["data_quality_flag"] = frame[flag].fillna("ok").astype(str) if flag in frame.columns else "ok"
    out["method"] = str(method)
    out["model_version"] = str(model_version or "")
    out["run_id"] = str(ctx["run_id"])
    out["use_case_id"] = str(ctx["use_case_id"])
    out["as_of_date"] = _inspire_date(ctx["as_of_date"])
    return out.sort_values(["segment_or_item", "rank"] if within in frame.columns else ["rank"])[[c for c, _ in INSPIRE_CORE_COLUMNS]]


