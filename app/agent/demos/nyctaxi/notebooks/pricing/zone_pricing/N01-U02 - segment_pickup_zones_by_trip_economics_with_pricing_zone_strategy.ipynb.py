def publish_results(spark, ctx, scored, evaluation, column_map, value_type, action_by_tier, model_version="", drift_psi=None,
                    action="run", out=print):
    status = "ok" if evaluation.get("skipped") or evaluation["decision"]["accepted"] or ctx["family"] == "E" else "rejected"
    if ctx["family"] not in INSPIRE_MODEL_FAMILIES and status == "rejected":
        write_run_log(spark, ctx, "rejected", action, metrics=evaluation.get("metrics"), baseline_metrics=evaluation.get("baseline"),
                      message=" ".join(evaluation["decision"]["reasons"]))
        raise InspireRejected(evaluation["decision"]["reasons"])
    frame = scored.copy()
    tier_column = column_map.get("tier")
    output = build_output_frame(frame, ctx, column_map, value_type, evaluation.get("method") or "approved model",
                                model_version, action_by_tier, column_map.get("significant"))
    if tier_column and tier_column in frame.columns:
        explicit = frame.reset_index(drop=True)[tier_column].reindex(output.index)
        output.loc[explicit.notna(), "priority_tier"] = explicit[explicit.notna()]
        output["recommended_action"] = output["priority_tier"].map(lambda t: dict(action_by_tier or {}).get(t, ""))
    rows = write_business_output(spark, output, ctx) if len(output) else 0
    reasons = " ".join((evaluation.get("decision") or {}).get("reasons") or [])
    write_run_log(spark, ctx, status, action, metrics=evaluation.get("metrics"), baseline_metrics=evaluation.get("baseline"),
                  rows_written=rows, model_version=model_version, drift_psi=drift_psi, watermark=evaluation.get("watermark", ""),
                  message=("candidate rejected; scored with the approved model: " + reasons) if status == "rejected" else reasons)
    out(f"Wrote {rows} row(s) to {ctx['output_table']} (status {status}). Latest rows: {ctx['latest_view']}.")
    return {"rows": rows, "status": status, "output": output}


def inspire_sql_literal(text):
    return "'" + str("" if text is None else text).replace("\\", "\\\\").replace("'", "\\'") + "'"


def _inspire_format_text(text):
    return " ".join(str(text or "").split()).replace("%", "%%")


def ai_endpoint_status(name):
    if not _ih_re.fullmatch(r"[A-Za-z0-9._-]{1,200}", str(name or "")):
        return False, "no valid AI endpoint name is set in the ai_endpoint widget"
    try:
        from databricks.sdk import WorkspaceClient
        endpoint = WorkspaceClient().serving_endpoints.get(name)
    except Exception as exc:
        return False, f"AI endpoint {name} is not available in this workspace ({str(exc)[:200]})"
    ready = str(getattr(getattr(endpoint, "state", None), "ready", "") or "")
    return ("READY" in ready.upper()), f"AI endpoint {name} state: {ready or 'unknown'}"


def inspire_temperature_rejected(message):
    text = str(message or "").lower()
    return "does not support the parameter" in text and "temperature" in text


def ai_model_parameters(ctx, max_tokens):
    params = f"'max_tokens', {int(max_tokens)}"
    if (ctx or {}).get("ai_temperature_supported", True):
        params += ", 'temperature', CAST(0.1 AS DOUBLE)"
    return f"named_struct({params})"


def _inspire_drop_temperature(ctx, endpoint, out):
    ctx["ai_temperature_supported"] = False
    out(f"AI endpoint {endpoint} does not accept a temperature parameter; the request is sent again without it.")


def explanation_sql(ctx, endpoint, decision, value_type, k=None, max_tokens=180):
    k = min(int(k or INSPIRE_EXPLANATION_TOP_K), INSPIRE_EXPLANATION_TOP_K)
    response_format = _ih_json.dumps({"type": "json_schema", "json_schema": {"name": "row_explanation", "strict": True, "schema": {
        "type": "object", "properties": {"explanation": {"type": "string"}}, "required": ["explanation"], "additionalProperties": False}}})
    prompt = (f"You explain one row of a ranked list to the person who owns this decision: {_inspire_format_text(decision)}. "
              "Use only the values below and add no number that is not given. Write at most two plain sentences and never write an em dash. "
              f"Entity: %s. {_inspire_format_text(value_type)}: %s. Rank: %s. Priority: %s. Reasons: %s. Recommended action: %s.")
    return (f"SELECT entity_id, segment_or_item, ai_query('{endpoint}', format_string({inspire_sql_literal(prompt)}, entity_label, CAST(ROUND(`value`, 4) AS STRING), "
            "CAST(`rank` AS STRING), priority_tier, array_join(top_reasons, '; '), recommended_action), "
            f"responseFormat => '{response_format}', modelParameters => {ai_model_parameters(ctx, max_tokens)}, "
            f"failOnError => false) AS ai_response FROM (SELECT * FROM {ctx['output_table']} WHERE run_id = '{ctx['run_id']}' "
            f"ORDER BY `rank`, entity_id LIMIT {k})")


def _inspire_response_field(df, column):
    fields = df.schema[column].dataType.fieldNames()
    return "response" if "response" in fields else "result"


def add_explanations(spark, ctx, decision, value_type, out=print):
    ok, note = ai_endpoint_status(ctx.get("ai_endpoint"))
    if not ok:
        out(f"Explanations skipped: {note}. The ranked list, reasons and actions are complete without them.")
        return {"explained": 0, "errors": 0, "skipped": note}
    staging = inspire_table_name(ctx["output_table"], f"_explain_{ctx['run_id']}")
    while True:
        query = explanation_sql(ctx, ctx["ai_endpoint"], decision, value_type)
        field = _inspire_response_field(spark.sql(query), "ai_response")
        spark.sql(f"CREATE OR REPLACE TABLE {staging} AS SELECT entity_id, segment_or_item, "
                  f"from_json(ai_response.{field}, 'explanation STRING').explanation AS explanation, ai_response.errorMessage AS error FROM ({query})")
        if not ctx.get("ai_temperature_supported", True):
            break
        rejected = spark.sql(f"SELECT FIRST(error, true) AS error FROM {staging} WHERE error IS NOT NULL").collect()
        if not (rejected and inspire_temperature_rejected(rejected[0]["error"])):
            break
        _inspire_drop_temperature(ctx, ctx["ai_endpoint"], out)
    try:
        counts = spark.sql(f"SELECT COUNT(*) AS n, SUM(CASE WHEN error IS NOT NULL OR explanation IS NULL THEN 1 ELSE 0 END) AS errors FROM {staging}").collect()[0]
        spark.sql(f"MERGE INTO {ctx['output_table']} AS t USING (SELECT * FROM {staging} WHERE explanation IS NOT NULL) AS s "
                  f"ON t.entity_id = s.entity_id AND t.segment_or_item = s.segment_or_item AND t.run_id = '{ctx['run_id']}' "
                  "WHEN MATCHED THEN UPDATE SET t.explanation = s.explanation")
    finally:
        spark.sql(f"DROP TABLE IF EXISTS {staging}")
    out(f"Explanations added for {int(counts['n']) - int(counts['errors'] or 0)} of {int(counts['n'])} top row(s); {int(counts['errors'] or 0)} failed and stay empty.")
    return {"explained": int(counts["n"]) - int(counts["errors"] or 0), "errors": int(counts["errors"] or 0)}


