def log_single_run(spark, ctx, evaluation, out=print):
    if ctx["smoke_test"]:
        return None
    try:
        import mlflow
        mlflow.set_experiment(experiment_path(spark, ctx))
        with mlflow.start_run(run_name=f"{ctx['use_case_id']} {ctx['as_of_date']}") as run:
            mlflow.log_params({"family": ctx["family"], "technique": ctx["technique"], "method": str(evaluation.get("method"))[:250],
                               "use_case_id": ctx["use_case_id"], "as_of_date": ctx["as_of_date"]})
            mlflow.log_metrics({k: float(v) for k, v in (evaluation.get("metrics") or {}).items() if _inspire_num(v) is not None})
            mlflow.log_dict({"decision": evaluation.get("decision"), "baseline": evaluation.get("baseline"),
                             "thresholds": ctx["thresholds"], "overrides": ctx.get("threshold_overrides")}, "inspire_run.json")
        return run.info.run_id
    except Exception as exc:
        out(f"MLflow logging skipped ({str(exc)[:200]}); the run log table still records this run.")
        return None


def evaluate_for_family(ctx, slots, action, spark=None):
    family = ctx["family"]
    if family in INSPIRE_MODEL_FAMILIES:
        if action["action"] != "train":
            return {"skipped": True, "reason": action["reason"]}
        return INSPIRE_FAMILY_EVALUATORS[family](ctx, slots)
    runners = {"E": run_forecasting, "F": run_analysis, "H": run_planning}
    if family == "G":
        evaluation = run_text_processing(ctx, slots, spark)
    elif family in runners:
        evaluation = runners[family](ctx, slots)
    else:
        raise ValueError(f"unknown execution family {family!r}")
    evaluation["mlflow_run_id"] = log_single_run(spark, ctx, evaluation)
    return evaluation


