def run_contract_check(spark, ctx, readiness_report, allow_zero_rows=False, source_text=None, out=print):
    table, runs = ctx["output_table"], ctx["runs_table"]
    columns = {f.name: f.dataType.simpleString() for f in spark.table(table).schema.fields}
    rows = int(spark.sql(f"SELECT COUNT(*) AS n FROM {table} WHERE run_id = '{ctx['run_id']}'").collect()[0]["n"])
    status_rows = spark.sql(f"SELECT status FROM {runs} WHERE run_id = '{ctx['run_id']}' ORDER BY logged_at DESC LIMIT 1").collect()
    status = status_rows[0]["status"] if status_rows else None
    if source_text is None:
        try:
            source_text = notebook_source()
        except Exception as exc:
            hits = [{"cell": -1, "line": 0, "api": "notebook source unavailable", "detail": str(exc)[:200]}]
    if source_text is not None:
        hits = find_banned_serverless_apis(notebook_code_cells(source_text))
    report = contract_report(columns, rows, status, (readiness_report or {}).get("status"), hits, allow_zero_rows)
    for check in report["checks"]:
        out(f"  {'PASS' if check['passed'] else 'FAIL'}  {check['check']}: {check['detail']}")
    if not report["passed"]:
        raise InspireContractFailed("Contract check FAILED: " + "; ".join(f"{c['check']} ({c['detail']})" for c in report["checks"] if not c["passed"]))
    out("Contract check PASSED: this notebook is done.")
    return report


