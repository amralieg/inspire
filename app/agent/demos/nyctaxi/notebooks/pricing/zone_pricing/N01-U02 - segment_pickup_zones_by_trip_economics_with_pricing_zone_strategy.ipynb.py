def register_and_select_model(ctx, evaluation, action, slots, spark, out=print):
    family = ctx["family"]
    if evaluation.get("skipped"):
        champion = champion_info(ctx["model_name"])
        if not champion:
            write_run_log(spark, ctx, "rejected", action["action"], message="no approved model to score with")
            raise InspireNoChampion(ctx["model_name"], "Run once with run mode Auto or Retrain to train and approve one.")
        return load_model_version(ctx["model_name"], "champion", champion["flavor"]), champion
    accepted = evaluation["decision"]["accepted"]
    if ctx["smoke_test"]:
        out("Smoke test: the candidate is not registered and no alias changes.")
        if not accepted:
            raise InspireRejected(evaluation["decision"]["reasons"])
        return evaluation["model"], {"version": "smoke", "flavor": "in-memory", "tags": {}}
    import mlflow
    from mlflow import MlflowClient
    from mlflow.models import infer_signature
    mlflow.set_registry_uri("databricks-uc")
    mlflow.set_experiment(experiment_path(spark, ctx))
    model = evaluation["model"]
    reference = evaluation.get("reference")
    example = reference.head(5) if reference is not None else evaluation["train"].head(5)
    prediction = slots["predict"](ctx, model, example) if family != "D" else slots["predict"](ctx, model, example[["entity_id"]].drop_duplicates(), 3)
    signature = infer_signature(example, prediction)
    tags = {"use_case_id": ctx["use_case_id"], "session_id": ctx["session_id"], "as_of_date": ctx["as_of_date"],
            "training_window": str(evaluation["metrics"].get("test_as_of", ctx["as_of_date"])),
            "holdout_metric": _ih_json.dumps({k: v for k, v in evaluation["metrics"].items() if _inspire_num(v) is not None}),
            "baseline_metric": _ih_json.dumps({k: v for k, v in evaluation["baseline"].items() if _inspire_num(v) is not None}),
            "row_counts": _ih_json.dumps({k: evaluation["metrics"].get(k) for k in ("train_rows", "test_rows") if k in evaluation["metrics"]}),
            "decision": evaluation["decision"]["decision"], "method": str(evaluation["method"])[:200]}
    try:
        import sklearn.base as _skb
        flavor = "sklearn" if isinstance(model, _skb.BaseEstimator) else "pyfunc"
    except ImportError:
        flavor = "pyfunc"
    tags["inspire_flavor"] = flavor
    with mlflow.start_run(run_name=f"{ctx['use_case_id']} {ctx['as_of_date']}"):
        mlflow.log_params({"family": family, "technique": ctx["technique"], "method": str(evaluation["method"])[:250]})
        mlflow.log_metrics({k: float(v) for k, v in evaluation["metrics"].items() if _inspire_num(v) is not None})
        if evaluation.get("feature_columns"):
            mlflow.log_dict(reference_profile(reference, evaluation["feature_columns"]), "inspire_reference_profile.json")
        try:
            if flavor == "sklearn":
                info = mlflow.sklearn.log_model(model, artifact_path="model", signature=signature, input_example=example,
                                                registered_model_name=ctx["model_name"])
            else:
                info = mlflow.pyfunc.log_model(artifact_path="model", python_model=inspire_wrapped_model(model), signature=signature,
                                               input_example=example, registered_model_name=ctx["model_name"])
        except Exception as exc:
            schema = ".".join(str(ctx["model_name"]).split(".")[:2])
            raise RuntimeError(f"Registering {ctx['model_name']} failed: {exc}. The user running this notebook needs CREATE MODEL and "
                               f"USE SCHEMA on {schema}, and USE CATALOG on its catalog.") from exc
    client = MlflowClient(registry_uri="databricks-uc")
    version = str(getattr(info, "registered_model_version", "") or max(int(v.version) for v in client.search_model_versions(f"name='{ctx['model_name']}'")))
    for key, value in tags.items():
        client.set_model_version_tag(ctx["model_name"], version, key, str(value))
    client.set_registered_model_alias(ctx["model_name"], "challenger", version)
    if accepted:
        client.set_registered_model_alias(ctx["model_name"], "champion", version)
        out(f"Version {version} passed acceptance and is now the champion of {ctx['model_name']}.")
    else:
        out(f"Version {version} did not pass acceptance; it stays the challenger. Reasons: {' '.join(evaluation['decision']['reasons'])}")
    champion = champion_info(ctx["model_name"], client)
    if not champion:
        write_run_log(spark, ctx, "rejected", action["action"], metrics=evaluation["metrics"], baseline_metrics=evaluation["baseline"],
                      model_version=version, message=" ".join(evaluation["decision"]["reasons"]))
        raise InspireNoChampion(ctx["model_name"], "The new candidate did not pass acceptance: " + " ".join(evaluation["decision"]["reasons"]))
    return load_model_version(ctx["model_name"], "champion", champion["flavor"]), champion


