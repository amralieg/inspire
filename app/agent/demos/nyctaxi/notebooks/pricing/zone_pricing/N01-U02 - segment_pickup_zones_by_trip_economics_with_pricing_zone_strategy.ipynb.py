def find_banned_serverless_apis(cell_sources):
    import ast
    banned_attrs = {"cache", "persist", "unpersist", "checkpoint", "localCheckpoint", "sparkContext", "rdd"}
    hits = []
    for index, source in enumerate(cell_sources):
        lines = [("" if ln.lstrip().startswith(("%", "!")) else ln) for ln in str(source).split("\n")]
        try:
            tree = ast.parse("\n".join(lines))
        except SyntaxError as exc:
            hits.append({"cell": index, "line": exc.lineno or 0, "api": "syntax error", "detail": str(exc)})
            continue
        for node in ast.walk(tree):
            if isinstance(node, ast.Attribute) and node.attr in banned_attrs:
                hits.append({"cell": index, "line": node.lineno, "api": "." + node.attr, "detail": "not supported on serverless compute"})
            elif isinstance(node, ast.Name) and node.id in ("SparkContext", "sc"):
                hits.append({"cell": index, "line": node.lineno, "api": node.id, "detail": "SparkContext is not available on serverless compute"})
            elif isinstance(node, ast.Call) and node.args and isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str):
                text = node.args[0].value
                target = node.func.attr if isinstance(node.func, ast.Attribute) else getattr(node.func, "id", "")
                if target in ("get", "set") and text.startswith("spark.databricks."):
                    hits.append({"cell": index, "line": node.lineno, "api": text, "detail": "spark.databricks.* configs are not available on serverless compute"})
                elif target == "sql" and _ih_re.search(r"(?i)\bCACHE\s+(LAZY\s+)?TABLE\b", text):
                    hits.append({"cell": index, "line": node.lineno, "api": "CACHE TABLE", "detail": "not supported on serverless compute"})
    return hits


def notebook_code_cells(source_text):
    cells, current = [], []
    for line in str(source_text).split("\n"):
        if line.strip() == "# COMMAND ----------":
            cells.append("\n".join(current))
            current = []
        elif line.startswith("# MAGIC") or line.startswith("# Databricks notebook source"):
            current.append("")
        else:
            current.append(line)
    cells.append("\n".join(current))
    return [c for c in cells if c.strip()]


def notebook_source(launcher_type=None):
    import base64
