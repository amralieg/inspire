def score_with_model(ctx, slots, evaluation, model, champion):
    import numpy as np
    family = ctx["family"]
    trained_now = not evaluation.get("skipped")
    profile = reference_profile(evaluation["reference"], evaluation["feature_columns"]) if trained_now and evaluation.get("feature_columns") else champion_profile(champion)
    features = list((profile or {}).get("feature_columns") or [])
    if family == "A":
        pdf = to_pandas_all(slots["build_inputs"](ctx, [_inspire_date(ctx["as_of_date"])], scoring=True), ctx)
    elif family == "B":
        pdf = to_pandas_all(slots["build_inputs"](ctx, "current"), ctx)
    elif family == "C":
        pdf = to_pandas_all(slots["build_inputs"](ctx, ctx["as_of_date"]), ctx)
    elif family == "D":
        users = to_pandas_all(slots["build_inputs"](ctx, ctx["as_of_date"]).select("entity_id").distinct(), ctx)
        return slots["predict"](ctx, model, users, int(slots.get("RECOMMENDATIONS_PER_ENTITY") or 10)), None
    else:
        raise ValueError(f"family {family} publishes its single-run result directly")
    cols = [c for c in features if c in pdf.columns] or _inspire_numeric_columns(pdf, ("entity_id", "as_of_date"))
    if pdf.empty:
        check = {"check": "scoring population", "observed": 0, "required": 1, "passed": False,
                 "message": f"No entity is open for scoring as of {ctx['as_of_date']}, so there is nothing to score this run."}
        raise InspireReadinessStop([check], {"family": family, "status": "not_ready", "checks": [check], "observed": {"scoring_rows": 0}})
    if family == "C":
        pdf["segment"] = [f"segment {s}" for s in np.asarray(slots["predict"](ctx, model, pdf[cols])).tolist()]
    else:
        pdf["score"] = np.asarray(slots["predict"](ctx, model, pdf[cols]), dtype=float)
    if family == "B":
        stored = (evaluation.get("metrics") or {}) if trained_now else _ih_json.loads((champion or {}).get("tags", {}).get("holdout_metric") or "{}")
        cut, review = _inspire_num(stored.get("alert_threshold")), _inspire_num(stored.get("review_threshold"))
        if cut is not None:
            pdf["inspire_tier"] = np.where(pdf["score"] > cut, "Act now", np.where(pdf["score"] > (review if review is not None else cut), "Review", "Monitor"))
    reasons = slots["explanation_inputs"](ctx, model, pdf[cols]) if "explanation_inputs" in slots else None
    pdf["top_reasons"] = list(reasons) if reasons is not None else top_reasons_from_zscores(pdf[cols])
    return pdf, psi_against_profile(profile, pdf)


