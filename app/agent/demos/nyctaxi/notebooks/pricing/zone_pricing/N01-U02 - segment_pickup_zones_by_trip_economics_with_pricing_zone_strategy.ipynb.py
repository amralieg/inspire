def collect_slots(namespace, family):
    names = INSPIRE_FAMILY_SLOTS[str(family).upper()]
    slots = {}
    for name in names:
        fn = namespace.get(name)
        if not callable(fn):
            raise InspireSlotNotFilled(name)
        slots[name] = fn
    for name, value in namespace.items():
        if name.isupper() and not name.startswith("INSPIRE_") and name not in slots:
            slots[name] = value
    return slots


def _inspire_limited(df, ctx):
    return df.limit(int(ctx["row_limit"])) if ctx.get("row_limit") else df


def to_pandas_sample(df, ctx, max_rows=None, seed=42):
    df = _inspire_limited(df, ctx)
    cap = int(max_rows or INSPIRE_TRAINING_SAMPLE_ROWS)
    total = df.count()
    if total > cap:
        df = df.sample(withReplacement=False, fraction=min(1.0, cap * 1.1 / total), seed=seed).limit(cap)
    return df.toPandas()


def to_pandas_all(df, ctx, max_rows=2000000):
    df = _inspire_limited(df, ctx)
    total = df.count()
    if total > max_rows:
        raise ValueError(f"The scoring population has {total} rows, above the in-notebook limit of {max_rows}. "
                         "Narrow build_inputs to the entities this decision acts on, or raise the limit deliberately.")
    return df.toPandas()


def training_as_of_dates(as_of_date, window_days, windows):
    as_of = _inspire_date(as_of_date)
    window = int(window_days)
    if window <= 0:
        raise InspireSlotNotFilled("OUTCOME_WINDOW_DAYS")
    return sorted(as_of - _ih_dt.timedelta(days=window * i) for i in range(1, max(2, int(windows)) + 1))


def _inspire_metric(fn, *args):
    try:
        value = float(fn(*args))
    except (ValueError, TypeError, ZeroDivisionError):
        return None
    return value if _ih_math.isfinite(value) else None


def _inspire_numeric_columns(pdf, exclude):
    import pandas as pd
    return [c for c in pdf.columns if c not in exclude and pd.api.types.is_numeric_dtype(pdf[c]) and not pd.api.types.is_bool_dtype(pdf[c])]


def _inspire_top_correlated(X, y, k=5):
    import numpy as np
    scores = {}
    for col in X.columns:
        values = X[col].astype(float)
        if values.std() and np.isfinite(values.std()):
            scores[col] = abs(np.corrcoef(values.fillna(values.median()), y)[0, 1])
    ranked = sorted((c for c in scores if np.isfinite(scores[c])), key=lambda c: -scores[c])
    return ranked[:k] or list(X.columns[:k])


def _inspire_baseline_classifier():
    from sklearn.impute import SimpleImputer
    from sklearn.linear_model import LogisticRegression
    from sklearn.pipeline import make_pipeline
    from sklearn.preprocessing import StandardScaler
    return make_pipeline(SimpleImputer(strategy="median"), StandardScaler(), LogisticRegression(class_weight="balanced", max_iter=1000))


def _inspire_robust_z(X):
    import numpy as np
    values = X.to_numpy(dtype=float)
    median = np.nanmedian(values, axis=0)
    mad = np.nanmedian(np.abs(values - median), axis=0) * 1.4826
    mad[mad == 0] = np.nan
    z = np.abs((values - median) / mad)
    return np.nan_to_num(np.nanmax(np.where(np.isfinite(z), z, np.nan), axis=1), nan=0.0)


def evaluate_supervised(ctx, slots):
    import numpy as np
    import pandas as pd
    from sklearn.metrics import average_precision_score, roc_auc_score
    dates = training_as_of_dates(ctx["as_of_date"], slots.get("OUTCOME_WINDOW_DAYS") or 0, slots.get("TRAINING_WINDOWS") or 6)
    frame = slots["build_inputs"](ctx, dates).join(slots["build_label"](ctx, dates), ["entity_id", "as_of_date"], "inner")
    pdf = to_pandas_sample(frame, ctx)
    pdf["as_of_date"] = pd.to_datetime(pdf["as_of_date"]).dt.date
    survival = ctx["technique"] == "Survival Analysis"
    target = ("duration", "event") if survival else ("label",)
    features = _inspire_numeric_columns(pdf, ("entity_id", "as_of_date") + target)
    test_date = max(pdf["as_of_date"]) if len(pdf) else None
    train, test = pdf[pdf["as_of_date"] < test_date], pdf[pdf["as_of_date"] == test_date]
    if train.empty or test.empty or not features:
        raise ValueError(f"The time-aware split needs at least two closed outcome windows and numeric features; "
                         f"got {len(train)} training row(s), {len(test)} test row(s) and {len(features)} feature(s).")
    y_train = train["event"].astype(int) if survival else train["label"].astype(int)
    base_cols = [c for c in (slots.get("BASELINE_FEATURES") or []) if c in features] or _inspire_top_correlated(train[features], y_train)
    baseline_model = _inspire_baseline_classifier().fit(train[base_cols], y_train)
    base_scores = baseline_model.predict_proba(test[base_cols])[:, 1]
    if survival:
        def score(scores):
            return {"c_index": concordance_index(test["duration"], scores, test["event"])}
        candidates = slots["fit_candidates"](ctx, train[features], train[["duration", "event"]])
    else:
        y_test = test["label"].astype(int)
        def score(scores):
            return {"auc": _inspire_metric(roc_auc_score, y_test, scores), "pr_auc": _inspire_metric(average_precision_score, y_test, scores),
                    "class_rate": float(y_test.mean())}
        candidates = slots["fit_candidates"](ctx, train[features], y_train)
    baseline = dict(score(base_scores), features=base_cols, method="logistic regression on top signals")
    results = {name: score(np.asarray(slots["predict"](ctx, model, test[features]), dtype=float)) for name, model in dict(candidates).items()}
    if not results:
        raise InspireSlotNotFilled("fit_candidates")
    key = "c_index" if survival else "auc"
    best = max(results, key=lambda n: results[n].get(key) if results[n].get(key) is not None else -1.0)
    decision = accept_candidate("A", results[best], baseline, ctx["thresholds"], ctx["technique"])
    return {"model": candidates[best], "method": best, "metrics": dict(results[best], test_as_of=str(test_date), train_rows=len(train), test_rows=len(test)),
            "baseline": baseline, "decision": decision, "candidates": results, "feature_columns": features, "reference": train[features]}


def evaluate_anomaly(ctx, slots):
    import numpy as np
    th = ctx["thresholds"]
    ref = to_pandas_sample(slots["build_inputs"](ctx, "reference"), ctx)
    cur = to_pandas_all(slots["build_inputs"](ctx, "current"), ctx)
    features = _inspire_numeric_columns(ref, ("entity_id",))
    first, second = dict(slots["fit_candidates"](ctx, ref[features], 1)), dict(slots["fit_candidates"](ctx, ref[features], 2))
    budget = int(th["max_alerts_per_run"])
    results = {}
    for name, model in first.items():
        ref_scores = np.asarray(slots["predict"](ctx, model, ref[features]), dtype=float)
        s1 = np.asarray(slots["predict"](ctx, model, cur[features]), dtype=float)
        s2 = np.asarray(slots["predict"](ctx, second.get(name, model), cur[features]), dtype=float)
        cut = float(np.quantile(ref_scores, th["alert_quantile"]))
        review = float(np.quantile(ref_scores, max(0.0, 1.0 - 5.0 * (1.0 - th["alert_quantile"]))))
        alerts = int((s1 > cut).sum())
        results[name] = {"alerts": alerts, "topk_overlap": topk_overlap(s1, s2, min(len(cur), budget, max(10, alerts))),
                         "alert_threshold": cut, "review_threshold": review}
    if not results:
        raise InspireSlotNotFilled("fit_candidates")
    base_ref, base_cur = _inspire_robust_z(ref[features]), _inspire_robust_z(cur[features])
    baseline = {"method": "robust z-score", "alerts": int((base_cur > float(np.quantile(base_ref, th["alert_quantile"]))).sum())}
    best = max(results, key=lambda n: (results[n]["topk_overlap"] or 0.0, -results[n]["alerts"]))
    decision = accept_candidate("B", results[best], baseline, th, ctx["technique"])
    return {"model": first[best], "method": best, "metrics": results[best], "baseline": baseline, "decision": decision,
            "candidates": results, "feature_columns": features, "reference": ref[features]}


def evaluate_segmentation(ctx, slots):
    import numpy as np
    from sklearn.impute import SimpleImputer
    from sklearn.metrics import adjusted_rand_score, silhouette_score
    from sklearn.preprocessing import StandardScaler
    pdf = to_pandas_sample(slots["build_inputs"](ctx, ctx["as_of_date"]), ctx)
    features = _inspire_numeric_columns(pdf, ("entity_id",))
    X = pdf[features]
    Xs = StandardScaler().fit_transform(SimpleImputer(strategy="median").fit_transform(X))
    sample = min(10000, len(X))
    candidates = dict(slots["fit_candidates"](ctx, X, 42))
    rng = np.random.default_rng(42)
    results = {}
    for name, model in candidates.items():
        labels = np.asarray(slots["predict"](ctx, model, X))
        if len(set(labels.tolist())) < 2:
            results[name] = {"silhouette": None, "min_segment_share": None, "bootstrap_ari": None, "segments": 1}
            continue
        shares = np.unique(labels, return_counts=True)[1] / float(len(labels))
        aris = []
        for seed in (1, 2, 3):
            idx = rng.choice(len(X), size=len(X), replace=True)
            refit = dict(slots["fit_candidates"](ctx, X.iloc[idx], seed)).get(name)
            if refit is not None:
                aris.append(adjusted_rand_score(labels, np.asarray(slots["predict"](ctx, refit, X))))
        results[name] = {"silhouette": float(silhouette_score(Xs, labels, sample_size=sample, random_state=42)),
                         "min_segment_share": float(shares.min()), "bootstrap_ari": float(np.mean(aris)) if aris else None,
                         "segments": int(len(shares))}
    if not results:
        raise InspireSlotNotFilled("fit_candidates")
    top = Xs[:, int(np.argmax(np.var(Xs, axis=0)))]
    tiers = np.digitize(top, np.quantile(top, [1 / 3.0, 2 / 3.0]))
    baseline = {"method": "quantile tiers on the most variable feature",
                "silhouette": float(silhouette_score(Xs, tiers, sample_size=sample, random_state=42)) if len(set(tiers.tolist())) > 1 else None}
    best = max(results, key=lambda n: results[n]["silhouette"] if results[n]["silhouette"] is not None else -1.0)
    decision = accept_candidate("C", results[best], baseline, ctx["thresholds"], ctx["technique"])
    return {"model": candidates[best], "method": best, "metrics": results[best], "baseline": baseline, "decision": decision,
            "candidates": results, "feature_columns": features, "reference": X}


def _inspire_recommendation_lists(recs, k):
    ordered = recs.sort_values(["entity_id", "score"], ascending=[True, False])
    return {str(user): [str(i) for i in group["item_id"].tolist()[:k]] for user, group in ordered.groupby("entity_id")}


def evaluate_recommendation(ctx, slots):
    import pandas as pd
    interactions = to_pandas_sample(slots["build_inputs"](ctx, ctx["as_of_date"]), ctx)
    k = int(slots.get("RECOMMENDATIONS_PER_ENTITY") or 10)
    times = pd.to_datetime(interactions["event_time"])
    cutoff = times.quantile(0.8)
    train, test = interactions[times <= cutoff], interactions[times > cutoff]
    users = sorted(set(test["entity_id"].astype(str)) & set(train["entity_id"].astype(str)))
    if not users:
        raise ValueError("The out-of-time split found no entity with interactions on both sides of the cutoff.")
    relevant = {u: set(g["item_id"].astype(str)) for u, g in test.groupby(test["entity_id"].astype(str))}
    popular = train.groupby(train["item_id"].astype(str))["weight"].sum().sort_values(ascending=False).index.tolist()
    seen = {u: set(g["item_id"].astype(str)) for u, g in train.groupby(train["entity_id"].astype(str))}
    popularity = {u: [i for i in popular if i not in seen.get(u, set())][:k] for u in users}
    baseline = {"method": "most popular items", "precision_at_k": precision_at_k(popularity, relevant, k)}
    candidates = dict(slots["fit_candidates"](ctx, train))
    results = {}
    for name, model in candidates.items():
        recs = slots["predict"](ctx, model, pd.DataFrame({"entity_id": users}), k)
        results[name] = {"precision_at_k": precision_at_k(_inspire_recommendation_lists(recs.astype({"entity_id": str, "item_id": str}), k), relevant, k), "k": k}
    if not results:
        raise InspireSlotNotFilled("fit_candidates")
    best = max(results, key=lambda n: results[n]["precision_at_k"] or 0.0)
    decision = accept_candidate("D", results[best], baseline, ctx["thresholds"], ctx["technique"])
    return {"model": candidates[best], "method": best, "metrics": results[best], "baseline": baseline, "decision": decision,
            "candidates": results, "reference": None, "train": train}


def _inspire_future_periods(periods, horizon):
    import pandas as pd
    index = pd.DatetimeIndex(sorted(set(pd.to_datetime(periods))))
    freq = pd.infer_freq(index) if len(index) >= 3 else None
    if freq:
        return list(pd.date_range(start=index[-1], periods=int(horizon) + 1, freq=freq)[1:])
    step = pd.Series(index).diff().median() if len(index) >= 2 else pd.Timedelta(days=1)
    return [index[-1] + step * (i + 1) for i in range(int(horizon))]


def run_forecasting(ctx, slots):
    import numpy as np
    import pandas as pd
    th = ctx["thresholds"]
    series = to_pandas_all(slots["build_inputs"](ctx), ctx)
    series["period"] = pd.to_datetime(series["period"])
    season, horizon = int(slots.get("SEASON_LENGTH") or 0), int(slots.get("HORIZON") or 0)
    if season <= 0:
        raise InspireSlotNotFilled("SEASON_LENGTH")
    if horizon <= 0:
        raise InspireSlotNotFilled("HORIZON")
    keys = sorted(series["entity_id"].astype(str).unique())
    sample = keys if len(keys) <= INSPIRE_BACKTEST_SERIES else sorted(np.random.default_rng(42).choice(keys, INSPIRE_BACKTEST_SERIES, replace=False).tolist())
    backtest = series[series["entity_id"].astype(str).isin(set(sample))]
    periods = sorted(series["period"].unique())
    folds = int(th["min_backtest_folds"])
    model_errors, folds_run = [], 0
    for fold in range(1, folds + 1):
        end = len(periods) - fold * horizon - 1
        if end < season * 2:
            break
        cut, stop = periods[end], periods[min(len(periods) - 1, end + horizon)]
        history = backtest[backtest["period"] <= cut]
        actual = backtest[(backtest["period"] > cut) & (backtest["period"] <= stop)]
        predicted = slots["forecast"](ctx, history, horizon)
        predicted["period"] = pd.to_datetime(predicted["period"])
        joined = actual.merge(predicted, on=["entity_id", "period"], how="inner")
        for key, group in joined.groupby("entity_id"):
            past = history[history["entity_id"] == key].sort_values("period")["value"].to_numpy(dtype=float)
            score = mase(group["value"], group["forecast"], past, season)
            if score is not None:
                model_errors.append(score)
        folds_run += 1
    metrics = {"mase": float(np.mean(model_errors)) if model_errors else None, "backtest_folds": folds_run,
               "season_length": season, "horizon": horizon, "series": len(keys), "backtest_series": len(sample)}
    decision = accept_candidate("E", metrics, {"method": "seasonal naive"}, th, ctx["technique"])
    if decision["accepted"]:
        final = slots["forecast"](ctx, series, horizon)
        final["data_quality_flag"] = "ok"
        method = "model forecast (beats seasonal naive)"
    else:
        rows = []
        future = _inspire_future_periods(series["period"], horizon)
        for key, group in series.sort_values("period").groupby("entity_id"):
            for period, value in zip(future, seasonal_naive_forecast(group["value"].tolist(), season, horizon)):
                rows.append({"entity_id": key, "period": period, "forecast": value})
        final = pd.DataFrame(rows)
        final["data_quality_flag"] = "seasonal_naive_fallback"
        method = "seasonal naive (the model did not beat it)"
    final["period"] = pd.to_datetime(final["period"]).dt.date.astype(str)
    return {"scored": final, "method": method, "metrics": metrics, "baseline": {"method": "seasonal naive"}, "decision": decision}


def run_analysis(ctx, slots):
    th = ctx["thresholds"]
    findings = slots["analyze"](ctx, _inspire_limited(slots["build_inputs"](ctx), ctx)).copy()
    for col in ("entity_id", "value", "p_value", "n"):
        if col not in findings.columns:
            raise ValueError(f"analyze() must return a column named {col!r}; got {list(findings.columns)}")
    findings["q_value"] = bh_adjust(findings["p_value"].fillna(1.0).tolist()) if len(findings) else []
    findings["significant"] = (findings["q_value"] <= th["fdr_alpha"]) & (findings["n"] >= th["min_group_rows"])
    findings["abs_value"] = findings["value"].abs()
    metrics = {"findings": int(len(findings)), "significant_findings": int(findings["significant"].sum()), "multiple_testing": "BH",
               "fdr_alpha": th["fdr_alpha"]}
    decision = accept_candidate("F", metrics, {"method": "prior period or overall rate"}, th, ctx["technique"])
    return {"scored": findings, "method": "effect size with Benjamini-Hochberg corrected significance", "metrics": metrics,
            "baseline": {"method": "prior period or overall rate"}, "decision": decision}


